
CREATE TABLE IF NOT EXISTS public.usage_tracker (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier TEXT NOT NULL UNIQUE,
    usage_count INTEGER NOT NULL DEFAULT 0,
    last_reset TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- RLS Policies
ALTER TABLE public.usage_tracker ENABLE ROW LEVEL SECURITY;

-- Allow admin access
CREATE POLICY "Allow admin full access"
ON public.usage_tracker
FOR ALL
USING (true)
WITH CHECK (true);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_identifier ON public.usage_tracker(identifier);
